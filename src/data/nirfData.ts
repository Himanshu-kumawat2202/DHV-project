export const RANKINGS: RankingRecord[] = [];

// Generate consistent year-by-year ranking records
TRAJECTORIES.forEach((traj) => {
  const yearsCount = YEARS.length;
  YEARS.forEach((yr, index) => {
    // If institution only joined rankings in a later year (e.g. 2020)
    if (traj.joinedYear && yr < traj.joinedYear) {
      return;
    }

    const t = index / (yearsCount - 1);
    // Smooth progress with minor realistic noise
    const noise = Math.sin(yr * 3.7 + traj.startRank) * 0.4;
    const rankNoise = Math.round(Math.sin(yr * 2.1 + traj.startRank) * (traj.volatility || 1));

    const overall_score = Number(
      (traj.startScore + (traj.endScore - traj.startScore) * t + noise).toFixed(2)
    );

    let rank = Math.round(traj.startRank + (traj.endRank - traj.startRank) * t + rankNoise);
    if (rank < 1) rank = 1;

    // Small yearly drift on individual parameters
    const paramDrift = (paramBase: number) => {
      const val = paramBase + (Math.sin(yr * 1.5 + paramBase) * 1.5) + (t * 2);
      return Number(Math.min(100, Math.max(20, val)).toFixed(1));
    };

    RANKINGS.push({
      institution_id: traj.id,
      year: yr,
      category: traj.category,
      rank,
      overall_score,
      TLR: paramDrift(traj.tlr),
      RPC: paramDrift(traj.rpc),
      GO: paramDrift(traj.go),
      OI: paramDrift(traj.oi),
      PR: paramDrift(traj.pr),
    });
  });
});

